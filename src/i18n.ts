const dicts: Record<Lang, Record<Key, string>> = { en, id }
const locales: Record<Lang, string> = { en: 'en-US', id: 'id-ID' }

export function useI18n(): I18n {
  const lang = useSettings((s) => s.lang)
  return useMemo(() => makeI18n(lang), [lang])
}

/** Pure formatter set for a language; useI18n just picks the current one. */
export function makeI18n(lang: Lang): I18n {
  const locale = locales[lang]
  const t: I18n['t'] = (key, vars) => dicts[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? `{${k}}`))
  const num: I18n['num'] = (n, digits = 0) => n.toLocaleString(locale, { maximumFractionDigits: digits, minimumFractionDigits: digits })
  const qty: I18n['qty'] = (n) => n.toLocaleString(locale, { maximumFractionDigits: 8 })
  const money: I18n['money'] = (n) => `Rp${num(Math.round(n))}`
  const compact: I18n['compact'] = (n) => `Rp${n.toLocaleString(locale, { notation: 'compact', maximumFractionDigits: 1 })}`
  const change: I18n['change'] = (pct, digits = 2) =>
    pct === 0 ? `${num(0, digits)}%` : `${pct > 0 ? '▲ +' : '▼ −'}${num(Math.abs(pct), digits)}%`
  // Dates are calendar keys, not instants: format them in UTC so the day never shifts with the time zone.
  const month: I18n['month'] = (key, short = false) =>
    new Date(`${key}-01T00:00:00Z`).toLocaleDateString(locale, { month: short ? 'short' : 'long', year: short ? undefined : 'numeric', timeZone: 'UTC' })
  const day: I18n['day'] = (date) => new Date(`${date}T00:00:00Z`).toLocaleDateString(locale, { weekday: 'short', day: 'numeric', month: 'short', timeZone: 'UTC' })
  const category: I18n['category'] = (c) => (isBuiltIn(c) ? t(`cat.${c}` as Key) : c)
  return { lang, locale, t, num, qty, money, compact, change, month, day, category }
}
